    def setUp(self):
        self.schema = "ally_auth_test_" + uuid.uuid4().hex
        self.admin = create_engine(DSN, connect_args={"connect_timeout": 3})
        with self.admin.begin() as conn:
            conn.execute(text(f'CREATE SCHEMA "{self.schema}"'))
        self.engine = create_engine(
            DSN,
            connect_args={"connect_timeout": 3, "options": f"-csearch_path={self.schema}"},
        )

    def tearDown(self):
        self.engine.dispose()
        # Drop only the schema generated by this fixture, in an explicitly selected test DB.
        assert self.schema.startswith("ally_auth_test_") and self.schema[15:].isalnum()
        with self.admin.begin() as conn:
            conn.execute(text(f'DROP SCHEMA "{self.schema}" CASCADE'))
        self.admin.dispose()

    def migrate(self, revision="head", *, downgrade=False):
        config = Config(str(ROOT / "alembic.ini"))
        with self.engine.connect() as conn:
            config.attributes["connection"] = conn
            (command.downgrade if downgrade else command.upgrade)(config, revision)

    def reset_schema(self):
        conn = psycopg2.connect(DSN)
        conn.autocommit = True
        with conn.cursor() as cur:
            cur.execute("DROP SCHEMA public CASCADE; CREATE SCHEMA public;")
        conn.close()

